-- 1. Ensure the base tables exist
CREATE TABLE IF NOT EXISTS streams (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    search_title TEXT NOT NULL,
    year INT,
    torrent_title TEXT NOT NULL,
    info_hash TEXT NOT NULL UNIQUE,
    quality TEXT,
    size TEXT,
    seeders INT DEFAULT 0,
    leechers INT DEFAULT 0,
    magnet TEXT NOT NULL,
    provider TEXT NOT NULL,
    torrent_url TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS bulk_queue (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    year INT,
    status TEXT DEFAULT 'pending' CHECK (status IN ('pending', 'processing', 'completed', 'failed')),
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. Add columns FIRST so they exist before any indexes are created
ALTER TABLE streams ADD COLUMN IF NOT EXISTS tmdb_id INT;
ALTER TABLE bulk_queue ADD COLUMN IF NOT EXISTS tmdb_id INT;

-- 3. Now create all indexes safely
CREATE INDEX IF NOT EXISTS idx_streams_tmdb_id ON streams(tmdb_id);
CREATE INDEX IF NOT EXISTS idx_streams_search_title ON streams(search_title);
CREATE INDEX IF NOT EXISTS idx_streams_info_hash ON streams(info_hash);
CREATE INDEX IF NOT EXISTS idx_streams_tmdb_seeders ON streams(tmdb_id, seeders DESC);

CREATE UNIQUE INDEX IF NOT EXISTS idx_bulk_queue_tmdb_id ON bulk_queue(tmdb_id) WHERE tmdb_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_bulk_queue_status ON bulk_queue(status);
