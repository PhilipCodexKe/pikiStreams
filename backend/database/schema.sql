-- Streams Table: Stores strictly scraped torrent/magnet details matched by search title
CREATE TABLE IF NOT EXISTS streams (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    search_title TEXT NOT NULL,          -- Normalized movie title (e.g. 'avatar')
    year INT,                            -- Release year (e.g. 2009)
    torrent_title TEXT NOT NULL,         -- Scraped torrent release name (e.g. 'Avatar.2009.1080p.BluRay.x264')
    info_hash TEXT NOT NULL UNIQUE,      -- Extracted from magnet (prevents duplicates)
    quality TEXT,                        -- 1080p, 720p, 2160p, etc.
    size TEXT,                           -- 2.1GB, 800MB, etc.
    seeders INT DEFAULT 0,
    leechers INT DEFAULT 0,
    magnet TEXT NOT NULL,
    provider TEXT NOT NULL,              -- 'thepiratebay', 'yts', '1337x'
    torrent_url TEXT,                    -- Direct .torrent download URL (e.g. from YTS to skip DHT)
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- Fast index for instant lookups by search_title
CREATE INDEX IF NOT EXISTS idx_streams_search_title ON streams(search_title);
CREATE INDEX IF NOT EXISTS idx_streams_info_hash ON streams(info_hash);

-- Simple Bulk Queue: Just titles to crawl
CREATE TABLE IF NOT EXISTS bulk_queue (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL UNIQUE,
    year INT,
    status TEXT DEFAULT 'pending' CHECK (status IN ('pending', 'processing', 'completed', 'failed')),
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_bulk_queue_status ON bulk_queue(status);
