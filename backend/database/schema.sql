-- ====================================================================
-- 1. MOVIES INFRASTRUCTURE
-- ====================================================================

CREATE TABLE IF NOT EXISTS streams (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    search_title TEXT NOT NULL,
    year INT,
    torrent_title TEXT NOT NULL,
    info_hash TEXT NOT NULL UNIQUE,
    quality TEXT,
    size TEXT,
    seeders INT DEFAULT 0,
    leechers INT DEFAULT 0,
    magnet TEXT NOT NULL,
    provider TEXT NOT NULL,
    torrent_url TEXT,
    tmdb_id INT,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS bulk_queue (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    year INT,
    tmdb_id INT,
    status TEXT DEFAULT 'pending' CHECK (status IN ('pending', 'processing', 'completed', 'failed')),
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- Movie Indexes
CREATE INDEX IF NOT EXISTS idx_streams_tmdb_id ON streams(tmdb_id);
CREATE INDEX IF NOT EXISTS idx_streams_search_title ON streams(search_title);
CREATE INDEX IF NOT EXISTS idx_streams_info_hash ON streams(info_hash);
CREATE INDEX IF NOT EXISTS idx_streams_tmdb_seeders ON streams(tmdb_id, seeders DESC);

CREATE UNIQUE INDEX IF NOT EXISTS idx_bulk_queue_tmdb_id ON bulk_queue(tmdb_id) WHERE tmdb_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_bulk_queue_status ON bulk_queue(status);


-- ====================================================================
-- 2. TV SHOWS & EPISODES INFRASTRUCTURE
-- ====================================================================

-- Table A: TV Streams / Magnets (Arranged cleanly per Show, Season, and Episode or Full Season Pack)
CREATE TABLE IF NOT EXISTS tv_streams (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tmdb_id INT NOT NULL,                                  -- TMDB Show ID for quick direct lookup
    imdb_id TEXT,                                          -- IMDb Show ID
    show_title TEXT NOT NULL,                              -- e.g. "Breaking Bad"
    season INT NOT NULL,                                   -- e.g. 1
    episode INT,                                           -- e.g. 1 (NULL if it's a full season pack)
    is_season_pack BOOLEAN DEFAULT FALSE,                  -- TRUE if entire season torrent (S01 Complete)
    torrent_title TEXT NOT NULL,                           -- Clean release name (e.g., "Breaking.Bad.S01E01.1080p.x265-QxR")
    info_hash TEXT NOT NULL UNIQUE,                        -- Deduplication key across all providers
    quality TEXT,                                          -- '4K', '1080p', '720p', 'HDTV'
    codec TEXT,                                            -- 'x265', 'HEVC', 'x264', 'AV1'
    size TEXT,                                             -- e.g. '350 MB', '12.4 GB'
    seeders INT DEFAULT 0,
    leechers INT DEFAULT 0,
    magnet TEXT NOT NULL,
    provider TEXT NOT NULL,                                -- '1337x', 'torrentgalaxy', 'eztv', 'limetorrents'
    torrent_url TEXT,
    file_idx INT,                                          -- Specific episode file index inside a season pack
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- Table B: Bulk Queue for TV Shows (Feeder Pipeline)
CREATE TABLE IF NOT EXISTS bulk_tv_queue (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tmdb_id INT NOT NULL,
    imdb_id TEXT,
    title TEXT NOT NULL,
    year INT,
    season INT DEFAULT 1,
    episode INT,                                           -- NULL = entire season pack or all episodes
    mode TEXT DEFAULT 'season_pack' CHECK (mode IN ('season_pack', 'episode', 'full_show')),
    status TEXT DEFAULT 'pending' CHECK (status IN ('pending', 'processing', 'completed', 'failed')),
    attempts INT DEFAULT 0,
    error_message TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- ====================================================================
-- 3. TV SHOWS INDEXES & PERFORMANCE OPTIMIZATIONS
-- ====================================================================

-- Indexes for instant stream retrieval by Episode or Season Pack ordered by seeders
CREATE INDEX IF NOT EXISTS idx_tv_streams_lookup ON tv_streams(tmdb_id, season, episode, seeders DESC);
CREATE INDEX IF NOT EXISTS idx_tv_streams_season_pack ON tv_streams(tmdb_id, season, is_season_pack, seeders DESC);
CREATE INDEX IF NOT EXISTS idx_tv_streams_info_hash ON tv_streams(info_hash);
CREATE INDEX IF NOT EXISTS idx_tv_streams_provider ON tv_streams(provider);

-- Indexes for the TV Bulk Feeder Queue
CREATE UNIQUE INDEX IF NOT EXISTS idx_bulk_tv_queue_job ON bulk_tv_queue(tmdb_id, season, episode, mode) WHERE status = 'pending';
CREATE INDEX IF NOT EXISTS idx_bulk_tv_queue_status ON bulk_tv_queue(status, created_at ASC);
